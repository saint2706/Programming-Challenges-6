"""Results writers: the Markdown summary and a self-contained HTML report.

Every value from a benchmark record is untrusted text as far as the HTML goes (an engine's error
message can contain anything), so each one passes through ``html.escape``. The HTML has no
scripts, no external resources and no network access; its charts are inline SVG.
"""

from __future__ import annotations

import html
import json
from pathlib import Path

BAR_LABEL_W = 260
BAR_W = 420
ROW_H = 22


def _num(x: object, nd: int = 3) -> str:
    if x is None:
        return "-"
    if isinstance(x, bool):
        return str(x)
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def _note(row: dict[str, object]) -> str:
    if row.get("status") == "ok":
        return ""
    return str(row.get("error") or row.get("status") or "")[:120].replace("\n", " ")


def _md_cell(x: object) -> str:
    return str(x).replace("|", "\\|").replace("\n", " ")


def _md_table(headers: list[str], rows: list[list[object]]) -> list[str]:
    out = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    out += ["| " + " | ".join(_md_cell(c) for c in r) + " |" for r in rows]
    return out


def summary_markdown(payload: dict[str, object]) -> str:
    """The Markdown summary: machine, the engine-by-query matrix and the scaling tables."""
    m = payload["machine"]  # type: ignore[index]
    lines = [
        "# Distributed Data Processing Pipeline: results",
        "",
        (
            "Generated by `uv run dist-pipeline report` from `results.json`. Times are wall-clock "
            "seconds for one query over the full input: the median of the timed repeats, with the "
            "inter-quartile range (IQR). Peak RSS is the largest sum of resident memory over the "
            "engine's process tree, sampled every 50 ms."
        ),
        "",
        "## Machine",
        "",
    ]
    for key in (
        "platform",
        "processor",
        "python",
        "cpu_physical",
        "cpu_logical",
        "ram_total_gb",
    ):
        lines.append(f"- {key}: {m.get(key)}")  # type: ignore[union-attr]
    lines += ["", "## Matrix", ""]
    rows = []
    for r in payload["matrix"]:  # type: ignore[union-attr]
        t = r.get("time") or {}
        rows.append(
            [
                r["scale"],
                r["fmt"],
                r["label"],
                r["query"],
                r["status"],
                _num(t.get("median")),
                _num(t.get("iqr")),
                _num(r.get("peak_rss_mb"), 1),
                _num(r.get("verified")),
                _num(r.get("max_rel_error"), 4),
                _note(r),
            ]
        )
    lines += _md_table(
        [
            "Scale",
            "Format",
            "Engine",
            "Query",
            "Status",
            "Median s",
            "IQR s",
            "Peak RSS MB",
            "Verified",
            "Max rel err",
            "Note",
        ],
        rows,
    )
    scaling = payload.get("scaling") or {}
    if scaling:
        lines += [
            "",
            f"## Scaling ({scaling['scale']}, mrpipe)",
            "",
            "### Strong (fixed input)",
            "",
        ]
        lines += _md_table(
            ["Query", "Workers", "Status", "Median s", "IQR s", "Peak RSS MB"],
            [
                [
                    s["query"],
                    s["workers"],
                    s["status"],
                    _num((s["time"] or {}).get("median")),
                    _num((s["time"] or {}).get("iqr")),
                    _num(s["peak_rss_mb"], 1),
                ]
                for s in scaling["strong"]
            ],
        )
        lines += ["", "### Weak (input grows with workers; not verified)", ""]
        lines += _md_table(
            [
                "Query",
                "Workers",
                "Part files",
                "Status",
                "Median s",
                "IQR s",
                "Peak RSS MB",
            ],
            [
                [
                    s["query"],
                    s["workers"],
                    s["parts"],
                    s["status"],
                    _num((s["time"] or {}).get("median")),
                    _num((s["time"] or {}).get("iqr")),
                    _num(s["peak_rss_mb"], 1),
                ]
                for s in scaling["weak"]
            ],
        )
    return "\n".join(lines) + "\n"


def _bar_svg(items: list[tuple[str, float | None, str]]) -> str:
    """Horizontal bars; ``None`` values print the status text instead of a bar."""
    top = max((v for _, v, _ in items if v is not None), default=1.0)
    width = BAR_LABEL_W + BAR_W + 90
    height = ROW_H * len(items) + 8
    out = [
        (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
            f'width="100%" role="img">'
        )
    ]
    for i, (label, value, status) in enumerate(items):
        y = i * ROW_H + 4
        out.append(f'<text x="0" y="{y + 15}" class="lbl">{html.escape(label)}</text>')
        if value is None:
            out.append(
                f'<text x="{BAR_LABEL_W}" y="{y + 15}" class="na">{html.escape(status)}</text>'
            )
            continue
        w = max(1.0, BAR_W * value / top)
        out.append(
            f'<rect x="{BAR_LABEL_W}" y="{y + 3}" width="{w:.1f}" height="14" class="bar"/>'
        )
        out.append(
            f'<text x="{BAR_LABEL_W + w + 6:.1f}" y="{y + 15}" class="val">{value:.3f} s</text>'
        )
    out.append("</svg>")
    return "".join(out)


CSS = """
:root { --fg:#1d2330; --muted:#5b6475; --bg:#ffffff; --bar:#2f6fb0; --line:#d8dde6; }
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) { --fg:#e6e9ef; --muted:#9aa3b2; --bg:#14171d;
    --bar:#6aa8e8; --line:#2c3340; }
}
:root[data-theme="dark"] { --fg:#e6e9ef; --muted:#9aa3b2; --bg:#14171d; --bar:#6aa8e8;
  --line:#2c3340; }
body { margin:0; padding:16px; background:var(--bg); color:var(--fg);
  font:15px/1.5 system-ui, sans-serif; }
main { max-width:960px; margin:0 auto; }
h1 { font-size:1.6rem; } h2 { font-size:1.2rem; margin-top:2rem; }
table { border-collapse:collapse; width:100%; font-size:0.9rem; }
th, td { border-bottom:1px solid var(--line); padding:4px 6px; text-align:left;
  vertical-align:top; }
.note { color:var(--muted); }
svg text { font: 13px system-ui, sans-serif; fill: var(--fg); }
svg .bar { fill: var(--bar); }
svg .na { fill: var(--muted); font-style: italic; }
.wrap { overflow-x:auto; }
"""


def render_html(payload: dict[str, object]) -> str:
    """One self-contained page: machine, a bar chart per query, the tables and scaling."""
    e = html.escape
    m = payload["machine"]  # type: ignore[index]
    matrix = payload["matrix"]  # type: ignore[index]
    scales = [s for s in ("12m", "1m") if any(r["scale"] == s for r in matrix)]  # type: ignore[union-attr]
    main_scale = scales[0] if scales else ""
    parts = [
        "<!doctype html>",
        '<html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        "<title>Pipeline benchmark results</title>",
        f"<style>{CSS}</style></head><body><main>",
        "<h1>Distributed Data Processing Pipeline: results</h1>",
        (
            '<p class="note">Median wall-clock seconds per query on the full Parquet input, '
            "from fresh processes. Bars are not to scale across queries.</p>"
        ),
        "<h2>Machine</h2><ul>",
    ]
    for key in (
        "platform",
        "processor",
        "python",
        "cpu_physical",
        "cpu_logical",
        "ram_total_gb",
    ):
        parts.append(f"<li>{e(key)}: {e(str(m.get(key)))}</li>")  # type: ignore[union-attr]
    parts.append("</ul>")
    if main_scale:
        parts.append(f"<h2>Median time per query ({e(main_scale)})</h2>")
        queries = []
        for r in matrix:  # type: ignore[union-attr]
            if r["scale"] == main_scale and r["query"] not in queries:
                queries.append(r["query"])
        for q in queries:
            items: list[tuple[str, float | None, str]] = []
            for r in matrix:  # type: ignore[union-attr]
                if r["scale"] != main_scale or r["query"] != q or r["fmt"] != "parquet":
                    continue
                median = (r.get("time") or {}).get("median")  # type: ignore[union-attr]
                ok = r["status"] == "ok" and median is not None
                label = f"{r['label']}" + (
                    "" if r["verified"] is not False else " (FAILED)"
                )
                items.append((label, median if ok else None, str(r["status"])))
            parts.append(f'<h3>{e(q)}</h3><div class="wrap">{_bar_svg(items)}</div>')
    parts.append('<h2>Matrix</h2><div class="wrap"><table><thead><tr>')
    heads = [
        "Scale",
        "Format",
        "Engine",
        "Query",
        "Status",
        "Median s",
        "IQR s",
        "Peak RSS MB",
        "Verified",
        "Max rel err",
        "Note",
    ]
    parts.append("".join(f"<th>{e(h)}</th>" for h in heads))
    parts.append("</tr></thead><tbody>")
    for r in matrix:  # type: ignore[union-attr]
        t = r.get("time") or {}
        cells = [
            r["scale"],
            r["fmt"],
            r["label"],
            r["query"],
            r["status"],
            _num(t.get("median")),
            _num(t.get("iqr")),
            _num(r.get("peak_rss_mb"), 1),
            _num(r.get("verified")),
            _num(r.get("max_rel_error"), 4),
            _note(r),
        ]
        parts.append("<tr>" + "".join(f"<td>{e(str(c))}</td>" for c in cells) + "</tr>")
    parts.append("</tbody></table></div>")
    scaling = payload.get("scaling") or {}
    if scaling:
        parts.append(f"<h2>Scaling ({e(str(scaling['scale']))}, mrpipe)</h2>")  # type: ignore[index]
        strong = scaling["strong"]  # type: ignore[index]
        items = [
            (
                f"{s['query']}, workers={s['workers']}",
                (s["time"] or {}).get("median"),
                str(s["status"]),
            )
            for s in strong
        ]
        items = [(lbl, v if st == "ok" else None, st) for lbl, v, st in items]
        parts.append(
            f'<h3>Strong scaling, median seconds</h3><div class="wrap">{_bar_svg(items)}</div>'
        )
        parts.append(
            '<p class="note">Weak-scaling runs are timed on a prefix of the input and '
            "are not verified; see summary.md.</p>"
        )
    parts.append("</main></body></html>")
    return "".join(parts)


def write_report(results_path: Path, out_dir: Path) -> tuple[Path, Path]:
    """Read ``results.json`` and write ``summary.md`` and ``report.html`` beside it."""
    payload = json.loads(results_path.read_text(encoding="utf-8"))
    out_dir.mkdir(parents=True, exist_ok=True)
    md = out_dir / "summary.md"
    page = out_dir / "report.html"
    md.write_text(summary_markdown(payload), encoding="utf-8", newline="\n")
    page.write_text(render_html(payload), encoding="utf-8", newline="\n")
    return md, page
