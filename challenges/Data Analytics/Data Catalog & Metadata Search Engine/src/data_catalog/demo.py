"""A demo estate spread over three kinds of source, and the evaluation run against it.

TPC-H (scale 0.01, generated by DuckDB) is split across a SQLite file, a DuckDB file and a folder of
Parquet; a synthetic `users.csv` (fake people) and `events.jsonl` sit next to them. No source
declares a foreign key, so the TPC-H specification's keys plus the two demo links are the ground
truth the inference is scored against.
"""

from __future__ import annotations

import json
import random
import sqlite3
from contextlib import closing
from pathlib import Path

import duckdb

from data_catalog.indexer import crawl_into
from data_catalog.store import Catalog

SQLITE_TABLES = ["customer", "orders", "nation"]
DUCKDB_TABLES = ["lineitem", "part", "supplier", "partsupp"]

TRUE_FKS = {
    ("lineitem", "l_orderkey", "orders", "o_orderkey"),
    ("lineitem", "l_partkey", "part", "p_partkey"),
    ("lineitem", "l_suppkey", "supplier", "s_suppkey"),
    ("orders", "o_custkey", "customer", "c_custkey"),
    ("customer", "c_nationkey", "nation", "n_nationkey"),
    ("supplier", "s_nationkey", "nation", "n_nationkey"),
    ("nation", "n_regionkey", "region", "r_regionkey"),
    ("partsupp", "ps_partkey", "part", "p_partkey"),
    ("partsupp", "ps_suppkey", "supplier", "s_suppkey"),
    ("users", "customer_id", "customer", "c_custkey"),
    ("events", "user_id", "users", "id"),
}
TRUE_PII = {
    ("users", "first_name"),
    ("users", "last_name"),
    ("users", "email"),
    ("users", "phone"),
    ("users", "ip_address"),
    ("customer", "c_address"),
    ("customer", "c_phone"),
    ("supplier", "s_address"),
    ("supplier", "s_phone"),
}
# query -> relevant (dataset name, column or None for the dataset itself)
QUERIES: dict[str, set[tuple[str, str | None]]] = {
    "customer email": {("users", "email")},
    "phone number": {
        ("users", "phone"),
        ("customer", "c_phone"),
        ("supplier", "s_phone"),
    },
    "ship date": {("lineitem", "l_shipdate")},
    "extended price": {("lineitem", "l_extendedprice")},
    "order priority": {("orders", "o_orderpriority")},
    "supplier": {("supplier", None)},
    "nation": {("nation", None)},
    "discount": {("lineitem", "l_discount")},
    "ip address": {("users", "ip_address")},
    "signup": {("users", "signup_date")},
    "region": {("region", None)},
    "retail price": {("part", "p_retailprice")},
    "events": {("events", None)},
    "price": {("lineitem", "l_extendedprice"), ("part", "p_retailprice")},
    "segment": {("customer", "c_mktsegment")},
    "account balance": {("customer", "c_acctbal"), ("supplier", "s_acctbal")},
}

FIRST = [
    "Ada",
    "Grace",
    "Alan",
    "Edsger",
    "Barbara",
    "Donald",
    "Frances",
    "Ken",
    "Radia",
    "Tim",
]
LAST = [
    "Lovelace",
    "Hopper",
    "Turing",
    "Dijkstra",
    "Liskov",
    "Knuth",
    "Allen",
    "Thompson",
]


def build(out: Path, sf: float = 0.01) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / "files").mkdir(exist_ok=True)
    con = duckdb.connect()
    con.execute("INSTALL tpch; LOAD tpch;")
    con.execute(f"CALL dbgen(sf={float(sf)})")

    db = out / "sales.sqlite"
    db.unlink(missing_ok=True)
    with closing(sqlite3.connect(db)) as s:
        for t in SQLITE_TABLES:
            cols = con.execute(f"DESCRIBE {t}").fetchall()
            decl = ", ".join(
                f'"{c[0]}" '
                + (
                    "INTEGER"
                    if "INT" in c[1]
                    else "REAL"
                    if "DEC" in c[1] or "DOUBLE" in c[1]
                    else "TEXT"
                )
                for c in cols
            )
            s.execute(f'CREATE TABLE "{t}" ({decl})')
            rows = con.execute(f"SELECT * FROM {t}").fetchall()
            rows = [
                tuple(str(v) if hasattr(v, "isoformat") else v for v in r) for r in rows
            ]
            rows = [
                tuple(float(v) if type(v).__name__ == "Decimal" else v for v in r)
                for r in rows
            ]
            s.executemany(
                f'INSERT INTO "{t}" VALUES ({",".join("?" * len(cols))})', rows
            )
        s.commit()

    wh = out / "warehouse.duckdb"
    wh.unlink(missing_ok=True)
    con.execute(f"ATTACH '{wh.as_posix()}' AS wh")
    for t in DUCKDB_TABLES:
        con.execute(f"CREATE TABLE wh.{t} AS SELECT * FROM {t}")
    con.execute("DETACH wh")
    con.execute(f"COPY region TO '{(out / 'files' / 'region.parquet').as_posix()}'")

    custkeys = [r[0] for r in con.execute("SELECT c_custkey FROM customer").fetchall()]
    rng = random.Random(7)
    users = []
    for i in range(1, 501):
        f, last = rng.choice(FIRST), rng.choice(LAST)
        users.append(
            [
                i,
                f,
                last,
                f"{f}.{last}{i}@example.com".lower(),
                f"+1 555-{rng.randrange(100, 999)}-{rng.randrange(1000, 9999)}",
                f"10.{rng.randrange(256)}.{rng.randrange(256)}.{rng.randrange(1, 255)}",
                rng.choice(custkeys),
                f"2024-{rng.randrange(1, 13):02d}-{rng.randrange(1, 29):02d}",
            ]
        )
    head = "id,first_name,last_name,email,phone,ip_address,customer_id,signup_date"
    lines = [head] + [",".join(map(str, u)) for u in users]
    (out / "files" / "users.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    kinds = ["login", "view", "purchase", "logout"]
    with (out / "files" / "events.jsonl").open(
        "w", encoding="utf-8", newline="\n"
    ) as f:
        for e in range(1, 2001):
            rec = {
                "event_id": e,
                "user_id": rng.randrange(1, 501),
                "event": rng.choice(kinds),
            }
            f.write(json.dumps(rec) + "\n")


def _md_table(head: list[str], rows: list[list[str]]) -> str:
    w = [max(len(r[i]) for r in [head, *rows]) for i in range(len(head))]

    def fmt(r: list[str]) -> str:
        return "| " + " | ".join(c.ljust(w[i]) for i, c in enumerate(r)) + " |"

    return "\n".join([fmt(head), fmt(["-" * x for x in w]), *map(fmt, rows)]) + "\n"


def evaluate(demo_dir: Path, catalog_path: Path, out: Path) -> dict:
    catalog_path.unlink(missing_ok=True)
    with Catalog(catalog_path) as cat:
        summary = crawl_into(cat, [demo_dir])
        names = {d.key: d.name for d in cat.datasets()}
        found = {
            (
                names[r["child"]],
                r["child_column"],
                names[r["parent"]],
                r["parent_column"],
            )
            for r in cat.relations()
        }
        tp = found & TRUE_FKS
        fk = {
            "true_positives": len(tp),
            "false_positives": sorted(map(list, found - TRUE_FKS)),
            "missed": sorted(map(list, TRUE_FKS - found)),
            "precision": round(len(tp) / len(found), 3) if found else 0.0,
            "recall": round(len(tp) / len(TRUE_FKS), 3),
        }
        tagged = {
            (d.name, c.name)
            for d in cat.datasets()
            for c in d.columns
            if "pii" in c.tags
        }
        pii = {
            "tagged": sorted(map(list, tagged)),
            "precision": round(len(tagged & TRUE_PII) / len(tagged), 3)
            if tagged
            else 0.0,
            "recall": round(len(tagged & TRUE_PII) / len(TRUE_PII), 3),
        }
        search = {}
        for mode in ("like", "fts", "hybrid"):
            rr, hit5 = [], 0
            for q, relevant in QUERIES.items():
                hits = [
                    (h["name"], h["column"]) for h in cat.search(q, limit=10, mode=mode)
                ]
                rank = next((i + 1 for i, h in enumerate(hits) if h in relevant), None)
                rr.append(1 / rank if rank else 0.0)
                hit5 += bool(rank and rank <= 5)
            search[mode] = {
                "mrr": round(sum(rr) / len(rr), 3),
                "hit_at_5": f"{hit5}/{len(QUERIES)}",
            }
        per_query = {
            q: [f"{h['name']}.{h['column'] or '*'}" for h in cat.search(q, limit=3)]
            for q in QUERIES
        }
    result = {
        "datasets": len(names),
        "crawl": {"new": summary.new, "errors": summary.errors},
        "foreign_keys": fk,
        "pii": pii,
        "search": search,
        "top3_hybrid": per_query,
    }
    out.mkdir(parents=True, exist_ok=True)
    (out / "evaluation.json").write_text(
        json.dumps(result, indent=4) + "\n", encoding="utf-8", newline="\n"
    )
    md = f"# Catalog evaluation on the demo estate ({len(names)} datasets, 4 source kinds)\n\n"
    md += "## Foreign-key inference (no source declares any)\n\n"
    md += _md_table(
        ["Precision", "Recall", "True positives", "False positives", "Missed"],
        [
            [
                str(fk["precision"]),
                str(fk["recall"]),
                str(fk["true_positives"]),
                str(len(fk["false_positives"])),
                str(len(fk["missed"])),
            ]
        ],
    )
    for label, items in (
        ("False positives", fk["false_positives"]),
        ("Missed", fk["missed"]),
    ):
        for a, b, c, d in items:
            md += f"\n- {label}: `{a}.{b} -> {c}.{d}`"
    md = md.rstrip("\n") + "\n\n## PII tagging\n\n"
    md += _md_table(
        ["Precision", "Recall", "Tagged columns"],
        [
            [
                str(pii["precision"]),
                str(pii["recall"]),
                ", ".join(f"{a}.{b}" for a, b in pii["tagged"]),
            ]
        ],
    )
    md += f"\n## Search ({len(QUERIES)} labelled queries)\n\n"
    md += _md_table(
        ["Mode", "MRR", "Hit@5"],
        [[m, str(v["mrr"]), v["hit_at_5"]] for m, v in search.items()],
    )
    md += "\n## Top 3 hybrid hits per query\n\n"
    md += _md_table(
        ["Query", "Top 3"], [[q, ", ".join(h)] for q, h in per_query.items()]
    )
    (out / "evaluation.md").write_text(md, encoding="utf-8", newline="\n")
    return result
